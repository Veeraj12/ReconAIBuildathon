# Database
# https://docs.djangoproject.com/en/5.2/ref/settings/#databases
#
# Reads DATABASE_URL (e.g. Neon's Postgres connection string) from the
# environment / .env file. Falls back to the original local SQLite
# file automatically if DATABASE_URL isn't set — so a machine with no
# .env configured (e.g. a fresh clone, or CI) still works exactly as
# before, rather than crashing at import time. This is the ONLY file
# that needed to change to move databases — every model, migration,
# and .objects.create(...) call elsewhere is unaffected, since they
# all go through Django's ORM regardless of which engine sits
# underneath it.
import dj_database_url

DATABASE_URL = os.environ.get("DATABASE_URL")

if DATABASE_URL:
    DATABASES = {
        "default": dj_database_url.parse(
            DATABASE_URL,
            conn_max_age=600,   # keep connections open between requests instead of reconnecting every time
            ssl_require=True,   # Neon requires SSL — see .env.example's sslmode=require in the URL itself too
        )
    }
else:
    DATABASES = {
        "default": {
            "ENGINE": "django.db.backends.sqlite3",
            "NAME": BASE_DIR / "db.sqlite3",
        }
    }


