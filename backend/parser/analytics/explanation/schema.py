"""
Phase 3 — structured output schema.

This module now only defines the OUTPUT shape (`PatternExplanation` and
its nested dataclasses) — the API response contract. It intentionally
no longer contains `RESPONSE_JSON_SCHEMA` / `parse_and_ground` /
`GroundingError`: those existed to validate a JSON blob returned by an
external LLM, which no longer exists in this pipeline (see
ARCHITECTURE_PHASE3_LOCAL.md for the migration). Evidence grounding is
now `grounding.py`'s `EvidenceValidator` — a first-class pipeline
stage rather than a defensive parser around a third party's output.

CONFIDENCE, STILL DELIBERATELY QUALITATIVE
─────────────────────────────────────────────
`confidence_level` on a possible cause remains a 3-value enum
("high" | "medium" | "low") — now produced by `scoring.py`'s
documented, rule-based thresholds instead of requested-via-prompt from
an LLM. The reasoning that motivated this originally (never allow an
unmethodical "93% confidence") applies just as much to a local
deterministic score — see scoring.py's module docstring for the exact
formula and thresholds. Pattern-level confidence (Phase 2's
`PatternScorer` output) is passed through unchanged, same as before.
"""

from __future__ import annotations

from dataclasses import dataclass, field, asdict
from typing import Optional


CONFIDENCE_LEVELS = ("high", "medium", "low")


@dataclass
class PossibleCause:
    cause: str
    cause_id: str  # stable catalogue ID (e.g. "BANK_SERVICE_CHARGE") — see
                    # knowledge/schema.py; kept distinct from free-form
                    # `cause` text so a future human-feedback/learning loop
                    # (Phase 6) has something stable to key on.
    confidence_level: str  # one of CONFIDENCE_LEVELS
    supporting_evidence: list = field(default_factory=list)
    contradicting_evidence: list = field(default_factory=list)

    def to_dict(self) -> dict:
        return asdict(self)


@dataclass
class EvidenceReference:
    claim: str
    feature: str
    grounded: bool = True  # False if EvidenceValidator couldn't confirm this reference

    def to_dict(self) -> dict:
        return asdict(self)


@dataclass
class PatternExplanation:
    pattern_id: str
    summary: str
    facts: list = field(default_factory=list)
    possible_causes: list = field(default_factory=list)  # list[PossibleCause]
    unknowns: list = field(default_factory=list)
    recommended_investigation: str = ""
    evidence_references: list = field(default_factory=list)  # list[EvidenceReference]

    # Phase 2 pattern confidence, passed through unchanged — never
    # generated or altered by Phase 3.
    pattern_confidence: float = 0.0
    confidence_methodology: str = (
        "Cause confidence is a qualitative level (high/medium/low) computed by a local, "
        "rule-based scoring engine (see parser/analytics/explanation/scoring.py) from how "
        "many of a cause's documented supporting/contradicting conditions the pattern's "
        "own evidence satisfies — never a numeric probability, and never generated by an "
        "external model. Pattern confidence is a separate, deterministic score computed by "
        "Phase 2 from feature cohesion, unrelated to and not influenced by this explanation. "
        "A 'high' cause confidence means the available evidence is strongly compatible with "
        "that hypothesis — not that the cause has been proven."
    )

    # Always "deterministic_local" and always None respectively — no
    # external model is ever involved in generating this explanation.
    # Kept as explicit fields (rather than removed) so the API contract
    # stays stable and the frontend can render provenance honestly.
    status: str = "deterministic_local"
    model: Optional[str] = None

    generated_at: Optional[str] = None
    validation_warnings: list = field(default_factory=list)
    from_cache: bool = False

    def to_dict(self) -> dict:
        return {
            "pattern_id": self.pattern_id,
            "summary": self.summary,
            "facts": self.facts,
            "possible_causes": [c.to_dict() if isinstance(c, PossibleCause) else c for c in self.possible_causes],
            "unknowns": self.unknowns,
            "recommended_investigation": self.recommended_investigation,
            "evidence_references": [
                r.to_dict() if isinstance(r, EvidenceReference) else r for r in self.evidence_references
            ],
            "pattern_confidence": self.pattern_confidence,
            "confidence_methodology": self.confidence_methodology,
            "status": self.status,
            "model": self.model,
            "generated_at": self.generated_at,
            "validation_warnings": self.validation_warnings,
            "from_cache": self.from_cache,
        }
